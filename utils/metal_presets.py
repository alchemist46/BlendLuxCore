"""The metal presets of the Fresnel node (nodes/textures/fresnel) as the two
    colors of an F82-tint metal (OpenPBR, the Principled BSDF), used by the
    Metal Preset node (nodes/textures/metalpreset) and the EEVEE nodes"""
# <pep8 compliant>
import math

# The F82-tint metal (Kutz et al. 2021, OpenPBR's and Cycles' metal) has two
# colors: F0, the reflectance at normal incidence (OpenPBR base.color), and
# the tint, which scales the Schlick Fresnel at the cosine 1/7 (about 82
# degrees) to the metal's own (OpenPBR specular.color, the Principled BSDF's
# Specular Tint). Both are worked out per RGB channel from the n, k of the
# metal, as the Metal node does with a Fresnel texture, so that the
# reflectance matches the Metal node's exactly at 0 and 82 degrees and within
# a few percent at the other angles. The tint is capped at 1, as OpenPBR and
# Cycles cap it.
_F82_COS = 1 / 7


def conductor_fresnel(cos_theta, n, k):
    """The exact unpolarized Fresnel reflectance of a conductor (pyluxcore's
    FresnelTexture::GeneralEvaluate)"""
    c2 = cos_theta * cos_theta
    s2 = 1 - c2
    t0 = n * n - k * k - s2
    a2b2 = math.sqrt(t0 * t0 + 4 * n * n * k * k)
    a = math.sqrt(max(0, 0.5 * (a2b2 + t0)))
    t1 = a2b2 + c2
    t2 = 2 * a * cos_theta
    rs = (t1 - t2) / (t1 + t2)
    t3 = c2 * a2b2 + s2 * s2
    t4 = t2 * s2
    rp = rs * (t3 - t4) / (t3 + t4)
    return 0.5 * (rp + rs)


def nk_to_f82(n, k):
    """The F0 and F82 tint colors of the RGB complex IOR n, k"""
    f0 = []
    tint = []
    for n_c, k_c in zip(n, k):
        r0 = conductor_fresnel(1, n_c, k_c)
        schlick = r0 + (1 - r0) * (1 - _F82_COS) ** 5
        r82 = conductor_fresnel(_F82_COS, n_c, k_c)
        f0.append(r0)
        tint.append(min(1, r82 / schlick) if schlick > 0 else 1)
    return tuple(f0), tuple(tint)


def get_preset(preset, working_space):
    """The F0 and F82 tint colors of a Fresnel node preset in a working space
    (a scene.colorspace.working value, see utils/colorspace)"""
    spaces = METAL_PRESETS.get(preset, METAL_PRESETS["aluminium"])
    return spaces.get(working_space, spaces["rec709"])


